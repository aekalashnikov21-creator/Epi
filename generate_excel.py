f_bold = Font(size=10, bold=True)
f_note = Font(size=9, italic=True, color="666666")

fill_dark = PatternFill("solid", fgColor=DARK)
fill_light = PatternFill("solid", fgColor=LIGHT)

al_wrap = Alignment(wrap_text=True, vertical="top")
al_c = Alignment(horizontal="center", vertical="center", wrap_text=True)

thin = Side(style="thin", color="BBBBBB")
bord = Border(left=thin, right=thin, top=thin, bottom=thin)

wb = Workbook()
wb.remove(wb.active)

def sheet(name):
    ws = wb.create_sheet(name)
    ws.sheet_view.showGridLines = False
    return ws

def title(ws, text, sub):
    ws.merge_cells("A1:J1")
    c = ws["A1"]
    c.value = text
    c.font = f_title
    c.fill = fill_dark
    c.alignment = Alignment(vertical="center")
    ws.row_dimensions[1].height = 30
    ws.merge_cells("A2:J2")
    ws["A2"].value = sub
    ws["A2"].font = f_note
    return 4

def table(ws, row, headers, rows, widths, total=None, note=None):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    for c, h in enumerate(headers, 1):
        cell = ws.cell(row=row, column=c, value=h)
        cell.font = f_head
        cell.fill = fill_dark
        cell.alignment = al_c
        cell.border = bord
    row += 1
    for r in rows:
        for c, v in enumerate(r, 1):
            cell = ws.cell(row=row, column=c, value=v)
            cell.font = f_cell
            cell.alignment = al_wrap
            cell.border = bord
        row += 1
    if total:
        for c, v in enumerate(total, 1):
            cell = ws.cell(row=row, column=c, value=v)
            cell.font = f_bold
            cell.fill = fill_light
            cell.alignment = al_wrap
            cell.border = bord
        row += 1
    if note:
        row += 1
        ws.cell(row=row, column=1, value=note).font = f_note
    return row + 2

